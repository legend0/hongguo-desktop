/** 表情占位符匹配：`[中文名]`（名称限 1-10 字，防止误吞正文中的普通方括号内容） */
const EMOJI_PLACEHOLDER = /\[([^\[\]]{1,10})\]/g;

/**
 * 渲染弹幕文本：替换已收录的表情占位符为 emoji，未收录的原样保留。
 * @param text 原始弹幕文本（可能含 `[xx]` 占位符）
 * @returns 替换后的显示文本
 */
export function renderDanmakuText(text: string): string {
  return String(text ?? '').replace(EMOJI_PLACEHOLDER, (match, name: string) => DANMAKU_EMOJI[name] ?? match);
}
